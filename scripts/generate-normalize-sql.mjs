#!/usr/bin/env node
// Generate prisma/normalize.sql by reading the restored database (D27).
//
//   node scripts/generate-normalize-sql.mjs "$DATABASE_URL_UNPOOLED" > prisma/normalize.sql
//
// Why generate rather than hand-write: the schema has 17 tables, 142 columns,
// 45 indexes, 20 constraints, 16 sequences and 4 enums. Hand-writing ~150
// renames invites exactly one typo, and a typo here is a broken migration
// against production data.
//
// Why the output is committed and re-runnable: at cutover the database is
// re-dumped from Heroku, which still carries the original PascalCase schema,
// and the identical transformation must be applied to that final data.
//
// Renames are catalog operations — ALTER ... RENAME does not move a single
// row — which is why row counts on both sides are a sufficient proof that
// nothing was lost.

import { execFileSync } from 'node:child_process';

const conn = process.argv[2];
if (!conn) {
  console.error('usage: generate-normalize-sql.mjs <connection-string>');
  process.exit(2);
}

const PSQL = (() => {
  try {
    const brew = execFileSync('brew', ['--prefix', 'libpq'], { encoding: 'utf8' }).trim();
    return `${brew}/bin/psql`;
  } catch {
    return 'psql';
  }
})();

const query = (sql) =>
  execFileSync(PSQL, [conn, '--no-align', '--tuples-only', '--field-separator=\t', '-c', sql], {
    encoding: 'utf8',
  })
    .split('\n')
    .filter(Boolean)
    .map((line) => line.split('\t'));

/** camelCase / PascalCase -> snake_case, preserving acronym word boundaries. */
const snake = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();

const q = (id) => `"${id.replace(/"/g, '""')}"`;

// Objects owned by an extension (pg_stat_statements installs views and
// functions into public) must never be renamed.
const EXT_OWNED = `
  and c.oid not in (
    select objid from pg_depend where classid = 'pg_class'::regclass and deptype = 'e'
  )`;

const out = [];
const say = (s = '') => out.push(s);

say('-- Generated by scripts/generate-normalize-sql.mjs (D27). Do not hand-edit.');
say('-- Regenerate after any schema change, and re-apply after the cutover re-dump.');
say('--');
say('-- ALTER ... RENAME is a catalog operation: no row is read, written or moved,');
say('-- so this cannot silently mismap data the way a rewritten dump file could.');
say('-- Row counts are compared before and after to prove exactly that.');
say();
say('BEGIN;');
say();

// ---------------------------------------------------------------- drops
say('-- 1. Drop dead objects (D27).');
say('--    SequelizeMeta is the old ORM migration ledger, replaced by Prisma.');
say('--    password and salt are NULL for every user and unpopulatable under');
say('--    passwordless auth (D26) — carrying dead credential columns forward');
say('--    is the kind of thing a later audit rightly asks about.');
say('DROP TABLE IF EXISTS "SequelizeMeta";');
say('ALTER TABLE "Users" DROP COLUMN IF EXISTS "password";');
say('ALTER TABLE "Users" DROP COLUMN IF EXISTS "salt";');
say();
say('-- Users_uuid duplicates the index already backing Users_uuid_key.');
say('DROP INDEX IF EXISTS "Users_uuid";');
say();

// ---------------------------------------------------------------- enums
const enums = query(`
  select t.typname
  from pg_type t
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
  order by t.typname;
`).map(([name]) => name);

say('-- 2. Enum types.');
for (const name of enums) {
  const target = snake(name);
  if (target !== name) say(`ALTER TYPE ${q(name)} RENAME TO ${q(target)};`);
}
say();

// ---------------------------------------------------------------- columns
const columns = query(`
  select c.relname, a.attname
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid
  where n.nspname = 'public'
    and c.relkind = 'r'
    and a.attnum > 0
    and not a.attisdropped
    and c.relname <> 'SequelizeMeta'
    ${EXT_OWNED}
  order by c.relname, a.attnum;
`);

say('-- 3. Columns. Table names are still PascalCase at this point; tables are');
say('--    renamed last so every statement above can address them unambiguously.');
let currentTable = null;
for (const [table, column] of columns) {
  if (table === 'Users' && (column === 'password' || column === 'salt')) continue;
  const target = snake(column);
  if (target === column) continue;
  if (table !== currentTable) {
    say(`-- ${table}`);
    currentTable = table;
  }
  say(`ALTER TABLE ${q(table)} RENAME COLUMN ${q(column)} TO ${q(target)};`);
}
say();

// ---------------------------------------------------------------- constraints
const constraints = query(`
  select rel.relname, con.conname
  from pg_constraint con
  join pg_class rel on rel.oid = con.conrelid
  join pg_namespace n on n.oid = rel.relnamespace
  where n.nspname = 'public' and rel.relname <> 'SequelizeMeta'
  order by rel.relname, con.conname;
`);

say('-- 4. Constraints. Renaming a constraint also renames the index backing it.');
for (const [table, name] of constraints) {
  const target = snake(name);
  if (target !== name) {
    say(`ALTER TABLE ${q(table)} RENAME CONSTRAINT ${q(name)} TO ${q(target)};`);
  }
}
say();

// ---------------------------------------------------------------- indexes
const indexes = query(`
  select c.relname
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind = 'i'
    and c.oid not in (select conindid from pg_constraint where conindid <> 0)
    and c.relname <> 'Users_uuid'
    ${EXT_OWNED}
  order by c.relname;
`).map(([name]) => name);

say('-- 5. Indexes not backed by a constraint.');
for (const name of indexes) {
  const target = snake(name);
  if (target !== name) say(`ALTER INDEX ${q(name)} RENAME TO ${q(target)};`);
}
say();

// ---------------------------------------------------------------- sequences
const sequences = query(`
  select c.relname
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S' ${EXT_OWNED}
  order by c.relname;
`).map(([name]) => name);

say('-- 6. Sequences. Column defaults store the sequence as an OID, not as text,');
say('--    so the nextval() defaults follow the rename automatically.');
for (const name of sequences) {
  const target = snake(name);
  if (target !== name) say(`ALTER SEQUENCE ${q(name)} RENAME TO ${q(target)};`);
}
say();

// ---------------------------------------------------------------- tables
const tables = query(`
  select c.relname
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and c.relkind = 'r'
    and c.relname <> 'SequelizeMeta'
    ${EXT_OWNED}
  order by c.relname;
`).map(([name]) => name);

say('-- 7. Tables, last.');
for (const name of tables) {
  const target = snake(name);
  if (target !== name) say(`ALTER TABLE ${q(name)} RENAME TO ${q(target)};`);
}
say();
say('COMMIT;');
say();

console.log(out.join('\n'));
